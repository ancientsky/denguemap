export type ForecastKey = Key;

export function ft(key: Key, vars?: Record<string, string | number>): string {
  const s: string = (getLang() === 'en' ? en : zh)[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

