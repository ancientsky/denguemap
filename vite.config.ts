/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import type { OutputBundle, OutputChunk } from 'rolldown';

// Routes that render on the shared MapLibre map (src/app.ts MAP_ROUTES), and every route the router knows
// (src/lib/router.ts ROUTES; not imported: the config loader wants no extension-less source imports).
// Unknown routes fall back to the map, as in the router.
const MAP_VIEWS = ['map', 'clusters', 'vector', 'imported'] as const;
const ROUTES = ['map', 'clusters', 'vector', 'trends', 'imported', 'about'];

/** Short content hash for the generated file name (FNV-1a; avoids needing Node typings in this config). */
function fnv1a(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193);
  return (h >>> 0).toString(36).padStart(7, '0');
}

/**
 * Map routes: start downloading MapLibre, the map host and the route's view chunk as soon as the HTML is parsed,
 * instead of after the entry chunk has loaded and run (index → dom → maplibre waterfall). A static
 * <link rel="modulepreload"> would make /trends and /about download MapLibre (~280 KB gz) too, so the build emits
 * a tiny external script (CSP: no inline scripts) that reads the route from location.hash and, once the
 * render-blocking stylesheet has loaded (so it never delays first paint), injects the preloads only for map
 * routes. The app's own dynamic import()s then reuse them (Vite's preload helper skips links that already exist).
 */
function mapRoutePreload(): Plugin {
  let base = '/';
  let asset: { fileName: string; source: string } | null = null;
  const closure = (bundle: OutputBundle, start: OutputChunk, skip: Set<string>, js: Set<string>, css: Set<string>) => {
    const queue = [start.fileName];
    while (queue.length) {
      const f = queue.shift()!;
      const c = bundle[f];
      if (!c || c.type !== 'chunk' || skip.has(f) || js.has(f)) continue;
      js.add(f);
      for (const s of c.viteMetadata?.importedCss ?? []) css.add(s);
      queue.push(...c.imports);
    }
  };
  return {
    name: 'denguemap:map-route-preload',
    apply: 'build',
    configResolved(c) {
      base = c.base;
    },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        const bundle = ctx.bundle;
        if (!bundle) return html;
        const chunks = Object.values(bundle).filter((c): c is OutputChunk => c.type === 'chunk');
        const byModule = (suffix: string) => chunks.find((c) => c.facadeModuleId?.replace(/\\/g, '/').endsWith(suffix));
        const entry = chunks.find((c) => c.isEntry);
        const host = byModule('/src/map/host.ts');
        if (!entry || !host) throw new Error('map-route-preload: entry or map host chunk not found');
        // Already loaded by index.html (entry + its static imports): never preload those again.
        const shell = new Set<string>();
        closure(bundle, entry, new Set(), shell, new Set());
        const common = new Set<string>(), commonCss = new Set<string>();
        closure(bundle, host, shell, common, commonCss);
        const perRoute: Record<string, string[]> = {};
        for (const r of MAP_VIEWS) {
          const view = byModule(`/src/views/${r}.ts`);
          if (!view) throw new Error(`map-route-preload: chunk for views/${r}.ts not found`);
          const js = new Set<string>(), css = new Set<string>();
          closure(bundle, view, new Set([...shell, ...common]), js, css);
          perRoute[r] = [...js, ...[...css].filter((f) => !commonCss.has(f))];
        }
        const files = { common: [...common, ...commonCss], routes: perRoute };
        const source = `// Generated by vite.config.ts (mapRoutePreload): preload MapLibre + the view chunk on map routes.
(function () {
  var f = ${JSON.stringify(files)}, routes = ${JSON.stringify(ROUTES)}, base = ${JSON.stringify(base)};
  var s = location.hash.replace(/^#\\/?/, ''), q = s.indexOf('?');
  var r = (q < 0 ? s : s.slice(0, q)).replace(/\\/+$/, '').toLowerCase();
  if (routes.indexOf(r) < 0) r = 'map';
  if (!f.routes[r]) return;
  // Wait for the render-blocking stylesheet (this script follows its <link>): MapLibre must not compete with it.
  var css = document.querySelector('link[rel="stylesheet"]');
  if (css && !css.sheet) {
    css.addEventListener('load', go);
    css.addEventListener('error', go);
  } else go();
  function go() {
    if (go.done) return;
    go.done = true;
    f.common.concat(f.routes[r]).forEach(function (p) {
      var l = document.createElement('link');
      if (/\\.css$/.test(p)) { l.rel = 'preload'; l.as = 'style'; } else l.rel = 'modulepreload';
      l.crossOrigin = '';
      l.href = base + p;
      document.head.appendChild(l);
    });
  }
})();
`;
        const hash = fnv1a(source);
        asset = { fileName: `assets/route-preload-${hash}.js`, source };
        // After the stylesheet <link> (the script waits for it to load), async: never blocks parsing or rendering.
        const tag = `<script async src="${base}${asset.fileName}"></script>`;
        const out = html.replace(/(<link rel="stylesheet"[^>]*>)/, `$1\n    ${tag}`);
        if (out === html) throw new Error('map-route-preload: stylesheet <link> not found in index.html');
        return out;
      },
    },
    generateBundle: {
      order: 'post',
      handler() {
        if (asset) this.emitFile({ type: 'asset', fileName: asset.fileName, source: asset.source });
      },
    },
  };
}

// GitHub Pages project site: https://ancientsky.github.io/denguemap/
export default defineConfig({
  base: '/denguemap/',
  plugins: [mapRoutePreload()],
  build: {
    target: 'es2022',
    // No inline scripts in the output (CSP script-src 'self'): disable the modulepreload polyfill.
    modulePreload: { polyfill: false },
    // Never inline assets as data: URLs (the MapLibre worker must be a same-origin file).
    assetsInlineLimit: 0,
    cssCodeSplit: true,
    sourcemap: false,
    reportCompressedSize: true,
    chunkSizeWarningLimit: 1200,
    rolldownOptions: {
      output: {
        codeSplitting: {
          groups: [
            // MapLibre is its own chunk (only loaded by map views).
            { name: 'maplibre', test: /node_modules[\\/]maplibre-gl[\\/]/, priority: 20 },
            // ECharts (+ zrender) is only imported by the lazily-loaded trends view.
            { name: 'echarts', test: /node_modules[\\/](echarts|zrender|tslib)[\\/]/, priority: 20 },
          ],
        },
      },
    },
  },
  preview: { port: 4173, strictPort: true },
  server: { port: 5173 },
  test: {
    include: ['tests/unit/**/*.test.ts', 'tests/data/**/*.test.mjs'],
    environment: 'node',
  },
});
